operand_1=int(input('enter the operand1: '))
operand_2=int(input('enter the operand2: '))

operator=input('Enter the opertor (+,-,*,/): ')

if operator== '+':
    print(operand_1 + operand_2)
elif operator=='-':
    print(operand_1 - operand_2)
elif operator== '*':
    print(operand_1 * operand_2)
elif operator== '/':
    print(operand_1 / operand_2)
else:
    print('None')

print('Thank you')
